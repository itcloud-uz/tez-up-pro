'use client';

import React from 'react';
import Link from 'next/link';
import { usePathname } from 'next/navigation';

export type UserRole = 'ADMIN' | 'EMPLOYEE' | 'COURIER' | 'CUSTOMER';

export interface NavItem {
  href: string;
  label: string;
  icon: React.ReactNode;
  roles: UserRole[];
  badge?: number;
}

export interface MobileNavProps {
  items: NavItem[];
  currentRole: UserRole;
}

export function MobileNav({ items, currentRole }: MobileNavProps) {
  const pathname = usePathname();

  const visibleItems = items.filter((item) => item.roles.includes(currentRole));

  if (visibleItems.length === 0) return null;

  return (
    <nav className="fixed bottom-0 inset-x-0 z-40 bg-white border-t border-[#E5E7EB] lg:hidden safe-area-bottom">
      <div
        className="flex items-stretch"
        style={{ paddingBottom: 'env(safe-area-inset-bottom)' }}
      >
        {visibleItems.map((item) => {
          const isActive =
            item.href === '/'
              ? pathname === '/'
              : pathname.startsWith(item.href);

          return (
            <Link
              key={item.href}
              href={item.href}
              className={[
                'flex-1 flex flex-col items-center justify-center gap-1 py-2 min-h-[56px]',
                'text-xs font-medium transition-colors duration-150',
                'focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-inset focus-visible:ring-[#FF6B35]',
                isActive ? 'text-[#FF6B35]' : 'text-[#6B7280]',
              ]
                .filter(Boolean)
                .join(' ')}
              aria-current={isActive ? 'page' : undefined}
            >
              <span className="relative flex items-center justify-center">
                <span
                  className={[
                    'flex items-center justify-center w-6 h-6 transition-transform duration-150',
                    isActive ? 'scale-110 text-[#FF6B35]' : 'text-[#6B7280]',
                  ]
                    .filter(Boolean)
                    .join(' ')}
                >
                  {item.icon}
                </span>
                {item.badge !== undefined && item.badge > 0 && (
                  <span className="absolute -top-1.5 -right-2 min-w-[16px] h-4 px-0.5 flex items-center justify-center rounded-full bg-[#FF6B35] text-white text-[10px] font-bold">
                    {item.badge > 99 ? '99+' : item.badge}
                  </span>
                )}
              </span>
              <span className="leading-none">{item.label}</span>
            </Link>
          );
        })}
      </div>
    </nav>
  );
}

